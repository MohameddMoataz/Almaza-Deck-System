export type TranslationKey = keyof typeof translations.en;

export function t(locale: Locale, key: TranslationKey, vars?: Record<string, string | number>) {
  let value: string = translations[locale][key] ?? translations.en[key];
  if (!vars) return value;

  Object.entries(vars).forEach(([name, replacement]) => {
    value = value.replaceAll(`{${name}}`, String(replacement));
  });

  return value;
}

export function sectionLabel(locale: Locale, section: "MAIN" | "EXTRA" | "EXTRA_CARDS" | "SIDE") {
  const labels = {
    MAIN: t(locale, "mainDeck"),
    EXTRA: t(locale, "fusionDeck"),
    EXTRA_CARDS: t(locale, "extraCards"),
    SIDE: t(locale, "sideDeck")
  };

  return labels[section];
}
